    def test_refuse_symlink_input_never_opened(self):
        """Direct unit assertion that builtins.open is never invoked on refused symlink target."""
        with tempfile.TemporaryDirectory() as td:
            target = Path(td) / "PRIMARY.BIN"
            target.write_bytes(b"CANARY_BYTES")
            link = Path(td) / "safe_name.bin"
            try:
                os.symlink(target, link)
            except (OSError, NotImplementedError, AttributeError):
                self.skipTest("symlinks not supported")

            with mock.patch("builtins.open", wraps=open) as mock_open:
                with self.assertRaises(ValueError) as cm:
                    preflight.run_preflight(str(link), str(FIXTURES_DIR / "valid_candidate.map"))
                self.assertIn("Security Violation", str(cm.exception))
                # Assert open() was never called with the symlink or target path
                opened_paths = [str(call[0][0]) for call in mock_open.call_args_list if call[0]]
                self.assertNotIn(str(link), opened_paths)
                self.assertNotIn(str(target), opened_paths)

