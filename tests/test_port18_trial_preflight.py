            self.assertEqual(report["candidate_size_bytes"], expected_size)
            self.assertEqual(report["candidate"]["sha256"], expected_sha256)
            self.assertEqual(report["candidate"]["size_bytes"], expected_size)

            # Check stderr prints for human operator
            self.assertIn(expected_sha256, res.stderr)
            self.assertIn(str(expected_size), res.stderr)

