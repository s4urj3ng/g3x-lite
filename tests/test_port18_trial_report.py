class TestPort18ReportParsing(unittest.TestCase):
    """Test parsing logic for fenced code blocks, raw files, and text variations."""

    def test_parse_fenced_markdown_file(self):
        with tempfile.TemporaryDirectory() as td:
            fixture_path = Path(td) / "valid_o1_report.md"
            fixture_path.write_text(FIXTURE_VALID_O1_REPORT, encoding="utf-8")
            data = report_tool.parse_report_file(fixture_path)
            self.assertEqual(data["candidate_sha256"], "0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef")
            self.assertEqual(data["candidate_size"], 211416)
            self.assertEqual(data["trial_date"], "2026-10-31")
            self.assertEqual(data["card_prepared"], "yes")
            self.assertEqual(data["camera_behaviour"], "normal_stock_boot")
            self.assertEqual(data["witness_observed"], "yes")
            self.assertEqual(data["trace_log_present"], "no")
            self.assertEqual(data["trace_log_path"], "none")
            self.assertEqual(data["witness_dump_path"], "none")
            self.assertEqual(data["outcome_id"], "O1")
            self.assertIn("CONT_ATTEMPTED", data["notes"])

    def test_parse_raw_unfenced_file(self):
        with tempfile.TemporaryDirectory() as td:
            fixture_path = Path(td) / "valid_o1_raw.txt"
            fixture_path.write_text(FIXTURE_VALID_O1_RAW, encoding="utf-8")
            data = report_tool.parse_report_file(fixture_path)
            self.assertEqual(data["candidate_size"], 211416)
            self.assertEqual(data["outcome_id"], "O1")
            self.assertEqual(data["candidate_sha256"], "0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef")

    def test_parse_report_with_surrounding_markdown(self):
        md = (
            "# Heading 1\nSome introductory text.\n"
            "```port18-report\n"
            + make_report_text(fenced=False)
            + "```\nTrailing comments and signature."
        )
        data = report_tool.parse_report_text(md)
        self.assertEqual(data["outcome_id"], "O1")
        self.assertEqual(data["camera_behaviour"], "normal_stock_boot")

    def test_reject_unclosed_fenced_block(self):
        bad_md = "```port18-report\ncandidate_sha256: none\n"
        with self.assertRaises(ValueError) as ctx:
            report_tool.parse_report_text(bad_md)
        self.assertIn("opening '```port18-report' fence found without matching closing", str(ctx.exception))

    def test_reject_empty_content(self):
        with self.assertRaises(ValueError) as ctx:
            report_tool.parse_report_text("   \n\n  ")
        self.assertIn("Empty report content", str(ctx.exception))

    def test_reject_malformed_line(self):
        bad_text = make_report_text().replace("card_prepared: yes", "card_prepared_yes_without_colon")
        with self.assertRaises(ValueError) as ctx:
            report_tool.parse_report_text(bad_text)
        self.assertIn("missing ':'", str(ctx.exception))

    def test_reject_duplicate_key(self):
        dup_text = f"```port18-report\n{make_report_text(fenced=False)}outcome_id: O2\n```\n"
        with self.assertRaises(ValueError) as ctx:
            report_tool.parse_report_text(dup_text)
        self.assertIn("Duplicate key in port18-report: 'outcome_id'", str(ctx.exception))

    def test_reject_unknown_key(self):
        unknown_text = f"```port18-report\n{make_report_text(fenced=False)}extra_secret_field: 123\n```\n"
        with self.assertRaises(ValueError) as ctx:
            report_tool.parse_report_text(unknown_text)
        self.assertIn("Unknown key in port18-report: 'extra_secret_field'", str(ctx.exception))

    def test_reject_missing_required_keys(self):
        # Missing outcome_id
        with tempfile.TemporaryDirectory() as td:
            fixture_path = Path(td) / "missing_key.md"
            fixture_path.write_text(FIXTURE_MISSING_KEY, encoding="utf-8")
            with self.assertRaises(ValueError) as ctx:
                report_tool.parse_report_file(fixture_path)
            self.assertIn("Missing required key(s) in port18-report: outcome_id", str(ctx.exception))

        # Test each required key individually missing
        for key in report_tool.REQUIRED_REPORT_KEYS:
            lines = [
                line for line in make_report_text(fenced=False).splitlines()
                if not line.startswith(f"{key}:")
            ]
            missing_text = "\n".join(lines)
            with self.assertRaises(ValueError) as ctx:
                report_tool.parse_report_text(missing_text)
            self.assertIn(f"Missing required key(s) in port18-report: {key}", str(ctx.exception))


