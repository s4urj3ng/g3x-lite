def make_report_text(
    candidate_sha256: str = "0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef",
    candidate_size: str | int = 211416,
    trial_date: str = "2026-10-31",
    card_prepared: str = "yes",
    camera_behaviour: str = "normal_stock_boot",
    witness_observed: str = "yes",
    trace_log_present: str = "no",
    trace_log_path: str = "none",
    witness_dump_path: str = "none",
    outcome_id: str = "O1",
    notes: str = "Observed CONT_ATTEMPTED / FRESHNESS_UNVERIFIED in Live View.",
    fenced: bool = True,
) -> str:
    """Helper to generate a synthetic port18-report text block."""
    lines = [
        f"candidate_sha256: {candidate_sha256}",
        f"candidate_size: {candidate_size}",
        f"trial_date: {trial_date}",
        f"card_prepared: {card_prepared}",
        f"camera_behaviour: {camera_behaviour}",
        f"witness_observed: {witness_observed}",
        f"trace_log_present: {trace_log_present}",
        f"trace_log_path: {trace_log_path}",
        f"witness_dump_path: {witness_dump_path}",
        f"outcome_id: {outcome_id}",
        f"notes: {notes}",
    ]
    body = "\n".join(lines)
    if fenced:
        return f"```port18-report\n{body}\n```\n"
    return body + "\n"


def make_synthetic_trace_bytes(records_count: int = 1) -> bytes:
    """Build valid synthetic PORT-17 trace binary bytes."""
    hdr = trace_parser.pack_header(capacity=64, write_idx=records_count, dropped_count=0)
    records = b""
    for i in range(records_count):
        records += trace_parser.pack_record(stage_id=1, tick=100 + i * 10, text=f"STAGE_{i}")
    return hdr + records


def make_synthetic_witness_bytes(
    stage_state: int = 7,
    expected_nonce: int = 0x12345678,
    corrupt_checksum: bool = False,
) -> bytes:
    """Build valid synthetic witness dump binary bytes."""
    magic = vwi.BOOT_WITNESS_MAGIC
    version = vwi.BOOT_WITNESS_VERSION
    loader_sp = 0x7FF8
    core_entry_pc = 0x003489B5
    cont_tick = 500

    checksum = None
    if corrupt_checksum:
        checksum = 0xDEADBEEF

    return vwi.pack_witness(
        magic, version, expected_nonce, stage_state, loader_sp, core_entry_pc, cont_tick, checksum=checksum
    )


