# 9b. PATH-SAFETY BYPASS REGRESSIONS (symlink '..' and 'none' sentinel)
# =============================================================================

class TestPort18PathSafetyBypassRegressions(unittest.TestCase):
    """Regressions for review findings P1 (lexical '..' before symlink resolution)
    and P2 ('none' sentinel exempted inside validate_path_safety)."""

    def setUp(self):
        self._old_cwd = os.getcwd()
        self._td = tempfile.TemporaryDirectory()
        self.td = Path(os.path.realpath(self._td.name))
        os.chdir(self.td)

    def tearDown(self):
        os.chdir(self._old_cwd)
        self._td.cleanup()

    def _write_report(self, name: str = "report.md", **kwargs) -> Path:
        report_file = self.td / name
        report_file.write_text(make_report_text(**kwargs), encoding="utf-8")
        return report_file

    def _run_cli(self, *args: str) -> subprocess.CompletedProcess:
        cmd = [sys.executable, str(TOOL_PATH), *args]
        return subprocess.run(
            cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, cwd=str(self.td)
        )

    def _assert_refused_everywhere(self, bad: str, expected: str) -> None:
        with self.assertRaises(ValueError) as ctx:
            report_tool.validate_path_safety(bad)
        self.assertIn(expected, str(ctx.exception))

        with self.assertRaises(ValueError) as ctx:
            report_tool.run_trace_parser(bad)
        self.assertIn(expected, str(ctx.exception))

        with self.assertRaises(ValueError) as ctx:
            report_tool.run_trace_parser(bad, use_subprocess=True)
        self.assertIn(expected, str(ctx.exception))

        with self.assertRaises(ValueError) as ctx:
            report_tool.run_witness_inspector(bad)
        self.assertIn(expected, str(ctx.exception))

        safe_report = self._write_report("safe_report.md")
        with self.assertRaises(ValueError) as ctx:
            report_tool.ingest_report(report_path=bad)
        self.assertIn(expected, str(ctx.exception))
        with self.assertRaises(ValueError) as ctx:
            report_tool.ingest_report(report_path=safe_report, trace_log_path=bad)
        self.assertIn(expected, str(ctx.exception))
        with self.assertRaises(ValueError) as ctx:
            report_tool.ingest_report(report_path=safe_report, witness_dump_path=bad)
        self.assertIn(expected, str(ctx.exception))

        for cli_args in (
            (bad,),
            (str(safe_report), "--trace-log", bad),
            (str(safe_report), "--witness-dump", bad),
        ):
            res = self._run_cli(*cli_args)
            self.assertEqual(res.returncode, 1, msg=f"{cli_args}: {res.stdout} {res.stderr}")
            self.assertIn("Phase 0 safety violation", res.stderr)
            self.assertIn(expected, res.stderr)
            self.assertEqual(res.stdout.strip(), "")

    @unittest.skipUnless(hasattr(os, "symlink"), "os.symlink unavailable on this platform")
    def test_p1_symlink_dotdot_into_firmware_dumps_refused(self):
        """alias -> <tmp>/firmware/dumps/nested; alias/../evidence.txt really resolves
        to <tmp>/firmware/dumps/evidence.txt and must be refused."""
        nested = self.td / "firmware" / "dumps" / "nested"
        nested.mkdir(parents=True)
        evidence = self.td / "firmware" / "dumps" / "evidence.txt"
        evidence.write_text("synthetic evidence text\n", encoding="utf-8")
        try:
            os.symlink(str(nested), str(self.td / "alias"))
        except (OSError, NotImplementedError) as exc:
            self.skipTest(f"cannot create symlink: {exc}")

        bad = "alias/../evidence.txt"
        # Sanity: lexical normalisation would hide the target; real resolution does not.
        self.assertEqual(os.path.normpath(bad), "evidence.txt")
        self.assertEqual(os.path.realpath(bad), str(evidence))

        self._assert_refused_everywhere(bad, "forbidden directory 'firmware/dumps/'")

        # Report field pointing through the same alias is refused too.
        report_file = self._write_report("field_report.md", trace_log_path=bad)
        with self.assertRaises(ValueError) as ctx:
            report_tool.ingest_report(report_path=report_file)
        self.assertIn("forbidden directory 'firmware/dumps/'", str(ctx.exception))

    @unittest.skipUnless(hasattr(os, "symlink"), "os.symlink unavailable on this platform")
    def test_p1_symlink_dotdot_to_primary_refused(self):
        """alias/../PRIMARY.BIN-style escapes are refused on the resolved basename."""
        real_dir = self.td / "real" / "inner"
        real_dir.mkdir(parents=True)
        (self.td / "real" / "PRIMARY.BIN").write_text("synthetic text only\n", encoding="utf-8")
        (self.td / "real" / "x").symlink_to(self.td / "real" / "PRIMARY.BIN")
        try:
            os.symlink(str(real_dir), str(self.td / "alias"))
        except (OSError, NotImplementedError) as exc:
            self.skipTest(f"cannot create symlink: {exc}")
        with self.assertRaises(ValueError) as ctx:
            report_tool.validate_path_safety("alias/../x")
        self.assertIn("matches forbidden pattern 'PRIMARY.*'", str(ctx.exception))

    def _make_none_symlink(self, target: Path) -> None:
        try:
            os.symlink(str(target), str(self.td / "none"))
        except (OSError, NotImplementedError) as exc:
            self.skipTest(f"cannot create symlink: {exc}")

    @unittest.skipUnless(hasattr(os, "symlink"), "os.symlink unavailable on this platform")
    def test_p2_none_symlink_to_primary_refused(self):
        """A real file named 'none' (symlink to a synthetic PRIMARY.BIN) is refused."""
        synth = self.td / "PRIMARY.BIN"
        synth.write_text("synthetic text only\n", encoding="utf-8")
        self._make_none_symlink(synth)
        self._assert_refused_everywhere("none", "matches forbidden pattern 'PRIMARY.*'")

    @unittest.skipUnless(hasattr(os, "symlink"), "os.symlink unavailable on this platform")
    def test_p2_none_symlink_to_firmware_dumps_refused(self):
        """A real file named 'none' (symlink into <tmp>/firmware/dumps/) is refused."""
        dumps = self.td / "firmware" / "dumps"
        dumps.mkdir(parents=True)
        target = dumps / "evidence.txt"
        target.write_text("synthetic evidence text\n", encoding="utf-8")
        self._make_none_symlink(target)
        self._assert_refused_everywhere("none", "forbidden directory 'firmware/dumps/'")

    def test_p2_validate_path_safety_has_no_sentinel_exemption(self):
        """validate_path_safety resolves 'none' as an ordinary path and returns it."""
        resolved = report_tool.validate_path_safety("none")
        self.assertEqual(resolved, self.td / "none")
        with self.assertRaises(ValueError):
            report_tool.validate_path_safety("")

    def test_p2_report_field_none_means_not_provided(self):
        """Report field 'none' still means 'not provided' and never runs a tool, even
        when a hostile file named 'none' exists in the cwd."""
        from unittest import mock

        if hasattr(os, "symlink"):
            synth = self.td / "PRIMARY.BIN"
            synth.write_text("synthetic text only\n", encoding="utf-8")
            self._make_none_symlink(synth)

        report_file = self._write_report(trace_log_path="none", witness_dump_path="none")
        with mock.patch.object(report_tool, "run_trace_parser") as m_trace, mock.patch.object(
            report_tool, "run_witness_inspector"
        ) as m_wit:
            summary = report_tool.ingest_report(report_path=report_file)
            self.assertEqual(summary["status"], "ok")
            self.assertEqual(summary["tool_results"], {})
            self.assertEqual(summary["parsed_fields"]["trace_log_path"], "none")
            self.assertEqual(summary["parsed_fields"]["witness_dump_path"], "none")

            # --trace-log / --witness-dump without an argument and a 'none' field
            # is an error, not a tool run.
            with self.assertRaises(ValueError):
                report_tool.ingest_report(report_path=report_file, trace_log_path="__FROM_REPORT__")
            with self.assertRaises(ValueError):
                report_tool.ingest_report(report_path=report_file, witness_dump_path="__FROM_REPORT__")
            m_trace.assert_not_called()
            m_wit.assert_not_called()

        res = self._run_cli(str(report_file))
        self.assertEqual(res.returncode, 0, msg=res.stderr)
        self.assertEqual(json.loads(res.stdout)["tool_results"], {})


